// Legal pages — /poveritelnost and /usloviya.
//
// Written for a sole photographer working as a natural person, not for a company.
// Three facts about this site shape the whole privacy policy, and all three were
// verified in the code rather than assumed:
//
//   1. There are no cookies, no analytics, no tracking pixels and no localStorage.
//   2. The fonts are self-hosted (src/app/styles/fonts.css), so no Google Fonts
//      request leaks a visitor's IP to a third party — that request alone is what
//      several EU rulings have found unlawful without consent.
//   3. The contact form has no backend. It opens the visitor's own mail client or
//      Gmail with a prefilled draft (contact-me.component.ts), so nothing reaches
//      Viktoria until the visitor presses send themselves.
//
// Together those mean the site needs no cookie banner at all — which is worth
// saying out loud on the page, because visitors have been trained to expect one.
//
// If any of that changes — an analytics tag, a form that POSTs, an embedded map or
// a YouTube iframe — the "Този сайт не ви следи" section becomes false and a
// consent banner becomes mandatory. Change this file in the same commit.

export type LegalBlock =
  | { kind: 'p'; text: string }
  | { kind: 'list'; items: string[] }
  | { kind: 'defs'; items: { term: string; text: string }[] };

